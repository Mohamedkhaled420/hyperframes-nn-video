#!/usr/bin/env node
/* Regenerates lib/api_bundle.mjs — the embedded data module that makes the
   serverless functions fully self-contained: no vercel.json includeFiles
   globs, no runtime fs reads for bundled data. Node file tracing always
   follows the import, so the data is guaranteed to reach every function.

   Run after changing any scene html, jobs.csv, narration_script.md or
   scene_docs/*.md:   node scripts/gen_api_bundle.mjs */
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const csv = await fsp.readFile(path.join(ROOT, 'jobs.csv'), 'utf8');
const order = csv.trim().split('\n').slice(1).map(r => r.split(',')[0].trim());

const scenes = [];
for (const folder of order) {
  const html = await fsp.readFile(path.join(ROOT, folder, 'index.html'), 'utf8');
  scenes.push({ folder, html });
}

const narration = await fsp.readFile(path.join(ROOT, 'narration_script.md'), 'utf8');

const docsDir = path.join(ROOT, 'scene_docs');
const docs = [];
for (const f of (await fsp.readdir(docsDir)).filter(f => f.endsWith('.md')).sort()) {
  docs.push({ file: f, md: await fsp.readFile(path.join(docsDir, f), 'utf8') });
}

/* studio authoring assets — the serverless /api/generate needs the engine,
   shell, authoring guide and example to assemble brand-new scenes */
const studio = {};
for (const f of ['engine.js', 'shell.html', 'scene_guide.md', 'example_scene.js']) {
  studio[f.replace(/\.\w+$/, '').replace(/[-_](\w)/g, (m, c) => c.toUpperCase())]
    = await fsp.readFile(path.join(ROOT, 'studio', f), 'utf8');
}

const out = `/* AUTO-GENERATED by scripts/gen_api_bundle.mjs — do not edit by hand.
   Embeds every byte the serverless functions need, so the deployment is
   self-contained on any host: no includeFiles globs, no fs reads.
   Regenerate with: node scripts/gen_api_bundle.mjs */
export const JOBS_CSV = ${JSON.stringify(csv)};

export const SCENES = ${JSON.stringify(scenes)};

export const NARRATION_MD = ${JSON.stringify(narration)};

export const SCENE_DOCS = ${JSON.stringify(docs)};

export const STUDIO = ${JSON.stringify(studio)};
`;

await fsp.writeFile(path.join(ROOT, 'lib', 'api_bundle.mjs'), out);
console.log('lib/api_bundle.mjs written:',
  scenes.length, 'scenes,', docs.length, 'docs,',
  narration.length + ' bytes narration,',
  (out.length / 1024).toFixed(0) + ' KB total');
